"""Generate a 2D occupancy map (PGM + YAML) of what the LiDAR sees on the field.

Only solids whose top is above the LiDAR scan plane are drawn. With the RCJ
field and Pinky Pro this is the outer walls only: the goal structure (0.11 m
with roof) is below the LiDAR (about 0.125 m). The map origin is chosen so the
field centre is the ``map`` origin, matching the simulator world origin.

    ros2 run pinky_soccer_field generate_field_map --output maps/rcj_field
"""

import argparse
import math
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

import numpy as np

from pinky_soccer_field.field_geometry import default_spec_path, Field

FREE, OCCUPIED, UNKNOWN = 254, 0, 205   # PGM grey values for map_server trinary mode
LIDAR_LINK = 'rplidar_link'
ROOT_LINK = 'base_footprint'


def lidar_height_from_urdf(urdf_xml, link=LIDAR_LINK, root=ROOT_LINK):
    """Return the z of ``link`` above ``root`` by chaining fixed joint origins.

    Joint rotations are ignored for the translation sum, which is exact for the
    Pinky chain (only yaw/pitch on the LiDAR branch, no offsets after tilt).
    """
    tree = ET.fromstring(urdf_xml)
    parent_of = {}
    for joint in tree.findall('joint'):
        child = joint.find('child').get('link')
        origin = joint.find('origin')
        xyz = [0.0, 0.0, 0.0]
        rpy = [0.0, 0.0, 0.0]
        if origin is not None:
            xyz = [float(v) for v in origin.get('xyz', '0 0 0').split()]
            rpy = [float(v) for v in origin.get('rpy', '0 0 0').split()]
        parent_of[child] = (joint.find('parent').get('link'), xyz, rpy)
    z, current, chain = 0.0, link, []
    while current != root:
        if current not in parent_of:
            raise ValueError(f'{link} is not connected to {root} in the URDF')
        parent, xyz, rpy = parent_of[current]
        chain.append((xyz, rpy))
        current = parent
    for xyz, rpy in chain:
        if abs(rpy[0]) > 1e-9 or abs(rpy[1]) > 1e-9:
            raise ValueError('Roll/pitch on the LiDAR chain is not supported')
        z += xyz[2]
    return z


def default_lidar_height():
    """Expand the soccer robot xacro (bumper on, defaults) and read the LiDAR height."""
    from ament_index_python.packages import get_package_share_directory
    import xacro
    path = Path(get_package_share_directory('pinky_soccer_description'),
                'urdf', 'soccer_robot.urdf.xacro')
    return lidar_height_from_urdf(xacro.process_file(str(path)).toxml())


def rasterize(field, resolution, lidar_height, margin=0.05):
    """Return (grid uint8 PGM values with row 0 = lowest y, origin_xy, obstacles used)."""
    seen = field.obstacles_seen_at(lidar_height)
    extent = max([abs(v) for o in seen for v in (o.rect.xmin, o.rect.xmax)]
                 + [field.inner_walls.xmax]) + margin
    extent_y = max([abs(v) for o in seen for v in (o.rect.ymin, o.rect.ymax)]
                   + [field.inner_walls.ymax]) + margin
    nx, ny = math.ceil(2 * extent / resolution), math.ceil(2 * extent_y / resolution)
    origin = (-nx * resolution / 2, -ny * resolution / 2)   # field centre = map origin
    xs = origin[0] + (np.arange(nx) + 0.5) * resolution
    ys = origin[1] + (np.arange(ny) + 0.5) * resolution
    gx, gy = np.meshgrid(xs, ys)
    grid = np.full((ny, nx), UNKNOWN, np.uint8)
    walls = field.inner_walls
    grid[(gx >= walls.xmin) & (gx <= walls.xmax) & (gy >= walls.ymin) & (gy <= walls.ymax)] = FREE

    def cells(lo, hi, start):
        # Cells that overlap [lo, hi]; at least one so thin walls are never lost.
        i0 = int(math.floor((lo - start) / resolution + 1e-9))
        i1 = int(math.ceil((hi - start) / resolution - 1e-9))
        return max(i0, 0), max(i1, i0 + 1)
    for o in seen:
        i0, i1 = cells(o.rect.xmin, o.rect.xmax, origin[0])
        j0, j1 = cells(o.rect.ymin, o.rect.ymax, origin[1])
        grid[j0:j1, i0:i1] = OCCUPIED
    return grid, origin, seen


def write_map(grid, origin, resolution, output, name='rcj_field'):
    """Write ``name``.pgm (row 0 = top = highest y) and ``name``.yaml for map_server."""
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    image = np.flipud(grid)
    pgm = output / f'{name}.pgm'
    with open(pgm, 'wb') as f:
        f.write(f'P5\n{image.shape[1]} {image.shape[0]}\n255\n'.encode())
        f.write(image.tobytes())
    yaml_path = output / f'{name}.yaml'
    yaml_path.write_text(
        f'# Generated by pinky_soccer_field generate_field_map. Do not edit by hand.\n'
        f'# Field centre = map origin; +X blue goal, -X yellow goal.\n'
        f'image: {name}.pgm\n'
        f'mode: trinary\n'
        f'resolution: {resolution}\n'
        f'origin: [{origin[0]:.6f}, {origin[1]:.6f}, 0.0]\n'
        f'negate: 0\n'
        f'occupied_thresh: 0.65\n'
        f'free_thresh: 0.25\n')
    return pgm, yaml_path


def main(argv=None):
    """Command line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--spec', default=None,
                        help='field YAML (default: pinky_soccer_sim config/rcj_field.yaml)')
    parser.add_argument('--output', default='maps/rcj_field')
    parser.add_argument('--resolution', type=float, default=0.01,
                        help='m/cell (default 0.01, an assumption to tune with AMCL)')
    parser.add_argument('--lidar-height', type=float, default=None,
                        help='scan plane height above the floor [m] (default: from URDF)')
    parser.add_argument('--urdf', default=None, help='URDF file to read the LiDAR height from')
    args = parser.parse_args(argv)
    if args.resolution <= 0:
        parser.error('--resolution must be positive')
    field = Field.from_file(args.spec or default_spec_path())
    if args.lidar_height is not None:
        height, source = args.lidar_height, 'argument'
    elif args.urdf:
        height, source = lidar_height_from_urdf(Path(args.urdf).read_text()), args.urdf
    else:
        height, source = default_lidar_height(), 'pinky_soccer_description xacro'
    grid, origin, seen = rasterize(field, args.resolution, height)
    pgm, yaml_path = write_map(grid, origin, args.resolution, args.output)
    print(f'LiDAR height {height:.4f} m ({source}); obstacles drawn: '
          f'{", ".join(o.name for o in seen) or "none"}')
    print(f'Wrote {pgm} and {yaml_path} ({grid.shape[1]}x{grid.shape[0]} cells)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
